const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const root = path.resolve(__dirname, '../../..');
const source = fs.readFileSync(path.join(root, 'shared/remote-desktop/ime.ts'), 'utf8');
const script = ts.transpileModule(source, { compilerOptions: {
  target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, newLine: ts.NewLineKind.LineFeed,
} }).outputText;
// Generate before Metro compiles to Hermes bytecode, where Function.toString() has no source text.
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport"
  content="width=device-width,initial-scale=1,maximum-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none';
    script-src 'unsafe-inline'; style-src 'unsafe-inline'">
  <style>*{box-sizing:border-box}html,body{margin:0;background:#111113;color:#eee;height:100%;overflow:hidden}
  textarea{width:100%;height:100%;resize:none;border:0;padding:8px 12px;background:transparent;
    color:#eee;font:16px system-ui;outline:none}textarea::placeholder{color:#999}
  </style></head><body><textarea autofocus rows="1" maxlength="1000" autocapitalize="off" autocorrect="off"
  spellcheck="false" aria-label="发送到电脑的文字" placeholder="输入文字，即时发送到电脑"></textarea><script>
  const exports = {};
  ${script.replace(/<\/script/gi, '<\\/script')}
  exports.bindDesktopIme(document.querySelector('textarea'), function(input) {
    window.ReactNativeWebView.postMessage(JSON.stringify(input));
  });document.querySelector('textarea').focus();</script></body></html>`;
const output = '// Generated by scripts/build-desktop-ime.cjs. Edit shared/remote-desktop/ime.ts.\n'
  + `export const desktopImeHtml = ${JSON.stringify(html)};\n`;
const target = path.join(root, 'apps/native/src/chat/desktop/desktopImeHtml.generated.ts');
const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
if (process.argv.includes('--check')) {
  if (previous !== output) throw new Error('Run node apps/native/scripts/build-desktop-ime.cjs');
} else if (previous !== output) fs.writeFileSync(target, output);
